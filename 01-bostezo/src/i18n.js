export function setLang(l) { lang = S[l] ? l : 'es'; document.documentElement.lang = lang; }
export function getLang() { return lang; }
export function detectLang() { const n = (navigator.language || 'es').toLowerCase(); return n.startsWith('es') || n.startsWith('ca') || n.startsWith('gl') || n.startsWith('eu') ? 'es' : 'en'; }
export function t(path, vars) {
  let v = path.split('.').reduce((o, k) => (o == null ? o : o[k]), S[lang]);
  if (v == null) v = path.split('.').reduce((o, k) => (o == null ? o : o[k]), S.es);
  if (typeof v === 'string' && vars) v = v.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return v ?? path;
}
