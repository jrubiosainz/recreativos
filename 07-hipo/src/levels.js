// HIPO: the six products on the poster. Each level is drawn in ASCII, one character per tile
// (1 tile = 25 cm; the hippo is a calf, the pool is not), read top to bottom:
//
//   solid   # deck tile   T pool wall   C concrete   W whitewash   M locker   G lawn   B brick
//           K kickboards  R slide plastic  D wood  S hedge  X crates
//   ledge   - rung/shelf  _ sunbed  = platform plank           (stand on it, hop up through it)
//   water   ~
//   things  @ start (standing on the tile below)   ! the edge you bomba off (standing on the tile below)
//           c plastic chair (run = seat)   u parasol (run = canopy)   o float   k inflatable croc
//           s springboard (run; anchored to the solid it touches)
//           h shower head (sprays down to the next floor)   f drinking fountain (stand still to drink)
//           z gaseosa   * PREMIO stick   t towel (checkpoint)   L lifeguard
//
// Anything drawn that is not a rule lives in `decor`.
import { EMPTY, SOLID, ONEWAY, WATER } from './sim.js';

const SOLIDS = '#TCWMGBKRDSX';
const LEDGES = '-_=';
const RUNS = { c: 'chair', u: 'parasol', o: 'float', k: 'croc', s: 'board' };
const REST = { chair: 0, parasol: 0.3, float: 0.55, croc: 0.55, board: 0 };

export function parse(L) {
  const rows = L.map, h = rows.length, w = Math.max(...rows.map((r) => r.length));
  const ch = (c, r) => (r >= 0 && r < h && c >= 0 && c < w ? rows[r][c] || '.' : '.');
  const tiles = new Uint8Array(w * h), look = new Uint8Array(w * h);
  const map = { w, h, tiles, look, start: null, goal: null, plats: [], showers: [], fountains: [], fizz: [], sticks: [], towels: [], guards: [] };
  const wetSide = (c, r) => ch(c - 1, r) === '~' || ch(c + 1, r) === '~';
  let nFloat = 0;
  for (let r = 0; r < h; r++) {
    for (let c = 0; c < w; c++) {
      const k = ch(c, r), i = r * w + c;
      if (SOLIDS.includes(k)) { tiles[i] = SOLID; look[i] = k.charCodeAt(0); continue; }
      if (LEDGES.includes(k)) { tiles[i] = ONEWAY; look[i] = k.charCodeAt(0); continue; }
      if (k === '~') { tiles[i] = WATER; continue; }
      tiles[i] = EMPTY;
      if ('*ztL'.includes(k) && wetSide(c, r)) tiles[i] = WATER;
      if (k === '@') map.start = { x: c + 0.5, y: r + 1, face: L.face || 1 };
      else if (k === '!') map.goal = { edge: L.dir > 0 ? c + 1 : c, y: r + 1, dir: L.dir, c, r };
      else if (k === 'h') map.showers.push({ c, r });
      else if (k === 'f') map.fountains.push({ x0: c - 0.35, y0: r, x1: c + 1.35, y1: r + 1, x: c + 0.5, y: r + 1 });
      else if (k === 'z') map.fizz.push({ x: c + 0.5, y: r + 0.5 });
      else if (k === '*') map.sticks.push({ x: c + 0.5, y: r + 0.5 });
      else if (k === 't') map.towels.push({ x: c + 0.5, y: r + 1 });
      else if (k === 'L') { const g = (L.guards || [])[map.guards.length] || {}; map.guards.push({ x: c + 0.5, y: r + 0.5, range: g.range || 0, face: g.face || -1 }); }
      else if (RUNS[k] && ch(c - 1, r) !== k) {
        let c1 = c; while (ch(c1 + 1, r) === k) c1++;
        const kind = RUNS[k], p = { kind, x0: c, x1: c1 + 1, rest: r + REST[kind], r };
        if (kind === 'board') p.anchor = SOLIDS.includes(ch(c - 1, r)) || LEDGES.includes(ch(c - 1, r)) ? -1 : 1;
        if (kind === 'float' || kind === 'croc') { const d = (L.drift || [])[nFloat++] || {}; p.amp = d.amp || 0; p.per = d.per || 4; p.ph = d.ph || 0; }
        map.plats.push(p);
      }
    }
  }
  // showers spray down to whatever they meet
  map.showers = map.showers.map(({ c, r }) => {
    let r1 = r + 1;
    while (r1 < h && tiles[r1 * w + c] !== SOLID && tiles[r1 * w + c] !== ONEWAY) r1++;
    return { x0: c - 0.15, y0: r + 0.6, x1: c + 1.15, y1: r1, c, r };
  });
  if (!map.start) throw new Error(`level ${L.id}: no start`);
  if (!map.goal) throw new Error(`level ${L.id}: no edge`);
  return map;
}

